// seed/seed.js
require('dotenv').config();
const mongoose = require('mongoose');
const bcrypt = require('bcryptjs');
const User = require('../backend/src/models/User');
const Email = require('../backend/src/models/Email');
const Conversation = require('../backend/src/models/Conversation');

const connect = async () => {
  await mongoose.connect(process.env.MONGODB_URI, { useNewUrlParser: true, useUnifiedTopology: true });
  console.log('MongoDB connected for seeding');
};

const createDemoUsers = async () => {
  const assistantExists = await User.findOne({ email: 'assistant@example.com' });
  const clientExists = await User.findOne({ email: 'client@example.com' });
  let assistant, client;
  if (!assistantExists) {
    const hash = await bcrypt.hash('Pass123!', 10);
    assistant = new User({ name: 'Demo Assistant', email: 'assistant@example.com', passwordHash: hash, role: 'assistant' });
    await assistant.save();
  } else {
    assistant = assistantExists;
  }
  if (!clientExists) {
    const hash = await bcrypt.hash('Pass123!', 10);
    client = new User({ name: 'Demo Client', email: 'client@example.com', passwordHash: hash, role: 'client' });
    await client.save();
  } else {
    client = clientExists;
  }
  // link them
  assistant.clientId = client._id;
  client.assistantId = assistant._id;
  await assistant.save();
  await client.save();
  console.log('Demo users ensured and linked');
  return { assistant, client };
};

const sampleSubjects = [
  'Meeting request for next Tuesday',
  'Your weekly newsletter',
  'Invoice #12345 attached',
  'Project approval needed',
  'Travel itinerary confirmation',
  'Client feedback on proposal',
  'Reschedule our call',
  'Urgent: contract signature',
  'Team outing invitation',
  'Reminder: deadline approaching',
];

const classifications = ['ASSISTANT_TO_REPLY','CLIENT_TO_REPLY','NO_REPLY_NEEDED','NEEDS_REVIEW'];

const randomItem = (arr) => arr[Math.floor(Math.random()*arr.length)];

const createSampleEmails = async (assistant, client) => {
  const existing = await Email.countDocuments();
  if (existing > 0) {
    console.log('Emails already seeded, skipping');
    return;
  }
  const emails = [];
  for (let i = 0; i < 20; i++) {
    const subject = randomItem(sampleSubjects);
    const classification = randomItem(classifications);
    const email = new Email({
      subject,
      sender: `sender${i}@example.com`,
      senderEmail: `sender${i}@example.com`,
      recipients: [assistant.email, client.email],
      body: `This is a autogenerated body for "${subject}". It contains details relevant to the classification.`,
      preview: subject.slice(0,30),
      clientId: client._id,
      assistantId: assistant._id,
      classification,
      originalAIClassification: classification,
      confidence: Math.random()*0.5 + 0.5,
      classificationSource: 'AI',
      summary: `Summary of ${subject}`,
      suggestedAction: classification === 'ASSISTANT_TO_REPLY' ? 'Check calendar and reply' : 'Forward to client',
      priority: classification === 'NO_REPLY_NEEDED' ? 'LOW' : 'HIGH',
    });
    await email.save();
    const conv = new Conversation({ emailId: email._id, participants: [email.senderEmail, assistant.email, client.email], messages: [{ author: email.senderEmail, body: email.body }], lastMessageAt: new Date() });
    await conv.save();
    email.conversationId = conv._id;
    await email.save();
    emails.push(email);
  }
  console.log(`Seeded ${emails.length} emails`);
};

const run = async () => {
  await connect();
  const { assistant, client } = await createDemoUsers();
  await createSampleEmails(assistant, client);
  mongoose.disconnect();
};

run().catch(err => { console.error(err); process.exit(1); });

